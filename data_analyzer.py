# Python Data Analyzer
# A beginner project for analyzing numerical data.

numbers = [120, 250, 180, 300, 150]

total = sum(numbers)
average = total / len(numbers)
highest = max(numbers)
lowest = min(numbers)

print("=== Python Data Analyzer ===")
print("Data:", numbers)
print("Number of values:", len(numbers))
print("Total:", total)
print("Average:", average)
print("Highest value:", highest)
print("Lowest value:", lowest)
